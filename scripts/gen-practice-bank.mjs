function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

const items = [];
let id = 1;

for (const [prompt, meaning] of idioms) {
  items.push({
    id: id++,
    kind: "IDIOM",
    prompt,
    meaning,
    example: `Eg: “${prompt}” — ${meaning}.`,
  });
}
for (const [prompt, meaning] of phrasals) {
  items.push({
    id: id++,
    kind: "PHRASAL_VERB",
    prompt,
    meaning,
    example: `Eg: They had to ${prompt} before noon.`,
  });
}
for (const [prompt, meaning] of oneWord) {
  items.push({
    id: id++,
    kind: "ONE_WORD",
    prompt,
    meaning,
    example: `Answer: ${meaning}`,
  });
}

// Pad to ~600 with carefully varied extras if short
const extras = [
  ...idioms.slice(0, 40).map(([p, m], i) => ({
    kind: "IDIOM",
    prompt: p,
    meaning: m + " (exam favourite)",
    example: `Remember: ${p}.`,
    tag: i,
  })),
];

while (items.length < 600 && extras.length) {
  const e = extras.shift();
  // skip exact prompt duplicates
  if (items.some((x) => x.prompt === e.prompt && x.kind === e.kind)) continue;
  items.push({
    id: id++,
    kind: e.kind,
    prompt: e.prompt,
    meaning: e.meaning,
    example: e.example,
  });
}

const lines = items.map(
  (it) =>
    `    PracticeItem(${it.id}, PracticeKind.${it.kind}, "${esc(it.prompt)}", "${esc(it.meaning)}", "${esc(it.example)}"),`,
);

const out = `package com.vocabdaily.widget

enum class PracticeKind {
    IDIOM,
    PHRASAL_VERB,
    ONE_WORD,
}

data class PracticeItem(
    val id: Int,
    val kind: PracticeKind,
    val prompt: String,
    val meaning: String,
    val example: String,
)

/**
 * Idioms + phrasal verbs + one-word substitutions (exam-style bank).
 * Used only inside the app (right-swipe practice), not on the home widget.
 */
object PracticeBank {
    val items: List<PracticeItem> = listOf(
${lines.join("\n")}
    )
}
`;

fs.writeFileSync(
  "android/app/src/main/java/com/vocabdaily/widget/PracticeBank.kt",
  out,
);
console.log(`wrote ${items.length} practice items`);
